            # try as vtt/srt xml
            # simple vtt parse fallback
            import re
            segs=[]
            time_pat=re.compile(r'(\d+:)?\d+:\d+\.\d+')
            cur_start=None; cur_text=[]
            def ts_to_sec(ts):
                ts=ts.strip().split(":")

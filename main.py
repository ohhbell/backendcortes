def analyze(transcript):
    moments=[]
    for i,seg in enumerate(transcript):
        score=50; cat="PICO"; reason="Fluxo"
        low=seg['text'].lower()
        if any(w in low for w in ["segredo","ninguém","truque","como","por que","erro"]): cat="GANCHO"; score+=25; reason="Gancho"
        if "?" in seg['text']: score+=10
        if seg['start']<60: score+=10
        moments.append({"id":i,"start":seg['start'],"end":seg['end'],"startFormatted":seg['startFormatted'],"endFormatted":seg['endFormatted'],"text":seg['text'],"category":cat,"score":min(99,score),"reason":reason,"viralHook":seg['text'][:60]})
    return sorted(moments,key=lambda x:x['score'],reverse=True)[:15]


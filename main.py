@app.post("/api/transcribe")
def transcribe(req: Req):
    vid=extract_id(req.url)
    if not vid: return {"error":"URL inválida"}
    print(f"=== {vid} ===")
    tr,src = try_yt_api(vid)
    if not tr:
        print("Fallback ytdlp")
        tr,src = try_ytdlp(vid)
    if not tr:
        print("Fallback piped")
        tr,src = try_piped(vid)
    if not tr:
        return {"error": f"YouTube bloqueou todas as 3 tentativas para {vid}. Solução: tente vídeo com LEGENDA MANUAL (não automática) ou me mande um proxy. Funciona 100% com vídeos do Flow/Cariani que têm legenda PT manual."}
    return {"success":True,"source":src,"transcript":tr,"moments":analyze(tr),"videoId":vid,"language":"pt"}
